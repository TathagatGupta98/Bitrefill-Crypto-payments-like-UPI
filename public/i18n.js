function readLanguage() {
  try {
    const fromUrl = new URLSearchParams(location.search).get('lang');
    if (fromUrl === 'hi' || fromUrl === 'en') {
      localStorage.setItem('sikka-lang', fromUrl);
      return fromUrl;
    }
    return localStorage.getItem('sikka-lang') === 'hi' ? 'hi' : 'en';
  } catch {
    return 'en';
  }
}

const LANG = readLanguage();
document.documentElement.lang = LANG;

const normalise = (text) => text.replace(/\s+/g, ' ').trim();

function t(english) {
  return LANG === 'hi' ? (HINDI[normalise(english)] ?? english) : english;
}

function translatePage(root = document.body) {
  if (LANG !== 'hi') return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    if (node.parentElement.closest('script, style, .no-translate')) continue;
    const key = normalise(node.textContent);
    if (HINDI[key]) node.textContent = node.textContent.replace(node.textContent.trim(), HINDI[key]);
  }
  document.querySelectorAll('[data-caption]').forEach((scene) => {
    scene.dataset.caption = t(scene.dataset.caption);
  });
}

function addLanguageSwitch() {
  const button = document.createElement('button');
  button.type = 'button';
  button.className = 'lang-switch no-translate';
  button.textContent = LANG === 'hi' ? 'English' : 'हिंदी';
  button.setAttribute('aria-label', LANG === 'hi' ? 'Switch to English' : 'Switch to Hindi');
  button.addEventListener('click', () => {
    const next = new URL(location.href);
    next.searchParams.set('lang', LANG === 'hi' ? 'en' : 'hi');
    location.href = next.href;
  });
  (document.getElementById('lang-slot') ?? document.querySelector('.nav-links'))?.prepend(button);
}

translatePage();
addLanguageSwitch();
